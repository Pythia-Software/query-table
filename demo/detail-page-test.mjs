import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const base = process.env.QT_DEMO_URL ?? 'http://127.0.0.1:5182';
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(new URL('/objects', base).href);
  await page.getByRole('button', { name: 'Open item call-1 in modal', exact: true }).waitFor();
  assert.equal(await page.locator('th[data-qt-field="__qt_item_details__"]').innerText(), 'Detail');
  assert.equal(await page.getByRole('button', { name: 'Preview item call-1', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Expand item call-1', exact: true }).count(), 0);
  const history = page.getByRole('group', { name: 'Query history', exact: true });
  assert.equal(await history.getByRole('button', { name: 'Reset', exact: true }).isVisible(), true);
  assert.equal(await history.innerText(), '');
  await page.getByRole('button', { name: 'Expand query builder', exact: true }).click();
  async function editor() {
    const expand = page.getByRole('button', { name: 'Expand query builder', exact: true });
    if (await expand.count()) await expand.click();
    await page.getByRole('button', { name: 'Customize columns', exact: true }).click();
    const modal = page.getByRole('dialog', { name: 'Select columns', exact: true });
    await modal.locator('.qt-editor-columns .qt-column-name').filter({ hasText: /^Detail$/ }).click();
    return modal;
  }
  let columns = await editor();
  assert.equal(await columns.getByRole('checkbox', { name: 'Include Modal', exact: true }).isChecked(), true);
  for (const label of ['Popover', 'Row expand', 'Page']) assert.equal(await columns.getByRole('checkbox', { name: `Include ${label}`, exact: true }).isChecked(), false);
  await columns.getByRole('checkbox', { name: 'Include Page', exact: true }).check();
  await page.screenshot({ path: '.context/detail-page-editor.png' });
  await columns.getByRole('button', { name: 'Apply columns', exact: true }).click();
  let link = page.getByRole('link', { name: 'Open item call-1 on page', exact: true });
  assert.equal(await link.getAttribute('target'), '_blank');
  const popupPromise = page.waitForEvent('popup');
  await link.click();
  const popup = await popupPromise;
  const details = popup.getByRole('dialog', { name: 'Item details', exact: true });
  await details.locator('dt').first().waitFor();
  assert.match(await details.innerText(), /npm run check/);
  await popup.close();
  columns = await editor();
  await columns.getByRole('textbox', { name: 'Page URL template', exact: true }).fill('/objects?item=');
  await columns.getByRole('combobox', { name: 'Insert URL placeholder', exact: true }).selectOption('{id}');
  await page.waitForFunction(() => document.querySelector('input[aria-label="Page URL template"]').value === '/objects?item={id}');
  await columns.getByRole('textbox', { name: 'Page URL template', exact: true }).fill('/objects?item={id}&tool={field:tool_name}&q={query}');
  await columns.getByRole('combobox', { name: 'Page link target', exact: true }).selectOption('_self');
  await columns.getByRole('button', { name: 'Apply columns', exact: true }).click();
  const href = await link.getAttribute('href');
  const constructed = new URL(href, base);
  assert.equal(constructed.searchParams.get('item'), 'call-1');
  assert.ok(constructed.searchParams.get('tool'));
  assert.ok(constructed.searchParams.get('q'));
  assert.equal(await link.getAttribute('target'), '_self');
  await link.click();
  await page.waitForURL(url => url.searchParams.get('item') === 'call-1');
  await link.waitFor();
  assert.equal(await link.getAttribute('target'), '_self');
  columns = await editor();
  const template = columns.getByRole('textbox', { name: 'Page URL template', exact: true });
  await template.fill('javascript:alert(1)');
  assert.equal(await columns.getByRole('button', { name: 'Apply columns', exact: true }).isDisabled(), true);
  assert.match(await columns.getByRole('alert').innerText(), /HTTP/);
  await columns.getByRole('button', { name: 'Cancel layout changes', exact: true }).click();
  assert.equal(await link.getAttribute('href'), href);
  await page.getByRole('button', { name: 'Open item call-1 in modal', exact: true }).click();
  const modal = page.getByRole('dialog', { name: 'Item details', exact: true });
  await modal.locator('dt').first().waitFor();
  assert.equal(await modal.locator('.qt-property-toolbar').getByRole('button', { name: 'Share', exact: true }).isVisible(), true);
  await modal.getByRole('button', { name: 'Share', exact: true }).click();
  const sharedUrl = await page.evaluate(() => navigator.clipboard.readText());
  const state = JSON.parse(Buffer.from(new URL(sharedUrl).searchParams.get('q'), 'base64url').toString());
  assert.deepEqual(state.d.active, { id: 'call-1', mode: 'modal' });
  assert.equal(state.d.page.target, '_self');
  await page.keyboard.press('Escape');
  await modal.waitFor({ state: 'detached' });
  // Icon controls still drive history when the builder is collapsed.
  await page.getByRole('button', { name: 'Collapse query builder', exact: true }).click();
  await history.getByRole('button', { name: 'Reset', exact: true }).click();
  await link.waitFor({ state: 'detached' });
  await history.getByRole('button', { name: 'Undo', exact: true }).click();
  await link.waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Expand query builder', exact: true }).click();
  columns = await editor();
  assert.equal(await columns.getByRole('textbox', { name: 'Page URL template', exact: true }).isVisible(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: '.context/detail-page-editor-mobile.png' });
  await page.keyboard.press('Escape');
  await page.screenshot({ path: '.context/detail-query-history-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  await context.close();
  console.log('PASS: Detail label, Modal-only default, Page built-in/new-tab and custom/same-tab navigation, URL state restoration, invalid/cancelled templates, toolbar Share, collapsed query history, mobile configuration.');
} finally { await browser.close(); }
