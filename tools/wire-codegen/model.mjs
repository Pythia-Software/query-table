// Shared reading of schema/query-wire.schema.json for the three emitters.
// See docs/wire-protocol.md for the x- keywords.
import { readFileSync } from "node:fs";

export function loadSchema(path) {
  const schema = JSON.parse(readFileSync(path, "utf8"));
  return { schema, defs: schema.$defs };
}
export const refName = (node) => node.$ref?.replace("#/$defs/", "");
/** The name a def carries in one language ("ts" | "go" | "swift"). */
export const typeName = (defs, name, lang) => defs[name][`x-${lang}-name`] ?? name;
/** A def whose language type is hand-written, or undefined. */
export const escapeHatch = (def, lang) => def[`x-${lang}-type`];
export const isObject = (def) => def.type === "object" && def.properties !== undefined;
export const isStringEnum = (def) => def.type === "string" && Array.isArray(def.enum);
export const variants = (node) => node.oneOf ?? node.anyOf;
/** `X | null` as { inner: X }; anything else as null. */
export function nullable(node) {
  const options = variants(node);
  if (!options || options.length !== 2) return null;
  const rest = options.filter((option) => option.type !== "null");
  return rest.length === 1 ? rest[0] : null;
}
/** A union whose every variant is a JSON scalar (incl. null). */
export function scalarUnion(defs, node) {
  const options = variants(node);
  return !!options && options.every((option) => {
    const target = option.$ref ? defs[refName(option)] : option;
    return ["string", "number", "integer", "boolean", "null"].includes(target.type) && !target.properties;
  });
}
export const properties = (def) => Object.entries(def.properties).map(([json, node]) => ({ json, node, required: (def.required ?? []).includes(json) }));
export const doc = (node, def) => node.description ?? (node.$ref ? def?.description : undefined);
/** `fooBar` → `FooBar`, with the Go initialism `ID`. */
export const pascal = (name) => name.replace(/^./, (c) => c.toUpperCase()).replace(/Id(?=[A-Z]|$)/g, "ID");
/** A string enum documented code by code with x-codes ({ code: { status, retry, description } }). */
export function codeEnum(def) {
  if (!def["x-codes"]) return null;
  const codes = def.enum.map((code) => ({ code, ...def["x-codes"][code] }));
  const extra = Object.keys(def["x-codes"]).filter((code) => !def.enum.includes(code));
  if (codes.some((c) => c.description === undefined) || extra.length) throw Error("x-codes must document exactly the enum's values.");
  return codes;
}
/** `snake_case` → `PascalCase`, with the Go initialisms `ID` and `JSON`. */
export const snakePascal = (name) => name.split("_").map((part) => ({ id: "ID", json: "JSON" })[part] ?? part.replace(/^./, (c) => c.toUpperCase())).join("");
/** `ErrorCode` → `ERROR_CODES`. */
export const constantList = (name) => name.replace(/(?<=[a-z])(?=[A-Z])/g, "_").toUpperCase() + "S";
export const banner =(comment) => `${comment} Code generated by tools/wire-codegen from schema/query-wire.schema.json. DO NOT EDIT.`;
